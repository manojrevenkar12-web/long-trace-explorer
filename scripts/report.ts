// Merges the benchmark outputs into reports/results.json (and the copy the home page reads,
// public/results.json) and writes REPORT.md. Every number in the README comes from here.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import os from "node:os";
import { rows } from "../src/server/clickhouse";

const read = (p: string) => (existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : null);
const pin = read("reports/heldout-pin.json");
type Any = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any
const merged: Any[] = [];
for (const set of ["dev", "heldout"]) {
  const server = read(`reports/bench-${set}.json`);
  if (!server) continue;
  const browser = read(`reports/browser-${set}.json`);
  for (const r of server.rows as Any[]) {
    const b = (browser?.rows as Any[] | undefined)?.find((x) => x.trace_id === r.trace_id);
    merged.push({ ...r, ...(b ? { browser: { windowed_first_rows_ms: b.windowed_first_rows_ms, windowed_heap_mb: b.windowed_heap_mb, full_first_rows_ms: b.full_first_rows_ms, full_heap_mb: b.full_heap_mb, ...(b.full_failed ? { full_failed: b.full_failed } : {}) } } : {}) });
  }
}
const [v] = await rows<{ v: string }>("SELECT version() AS v");
const cpu = os.cpus();
const results = {
  generated_at: new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC",
  machine: `${cpu.length} vCPU (${cpu[0]?.model.trim() ?? "unknown"}), ${Math.round(os.totalmem() / 2 ** 30)} GB RAM`,
  clickhouse: v.v,
  commit: (() => { try { return execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim(); } catch { return "uncommitted"; } })(),
  pinned: pin ? { heldout_sha256: pin.sha256, pinned_at: pin.pinned_at } : { heldout_sha256: "not pinned", pinned_at: "" },
  rows: merged,
};
const json = JSON.stringify(results, null, 2) + "\n";
writeFileSync("reports/results.json", json);
writeFileSync("public/results.json", json);

const ms = (x: number | null | undefined) => (x === null || x === undefined ? "n/a" : x >= 1000 ? `${(x / 1000).toFixed(2)} s` : `${Math.round(x)} ms`);
const mb = (b: number | null | undefined) => (b === null || b === undefined ? "n/a" : b >= 2 ** 20 ? `${(b / 2 ** 20).toFixed(1)} MB` : `${Math.round(b / 1024)} KB`);
const table = (set: string) => {
  const rs = merged.filter((r) => r.set === set);
  if (!rs.length) return "_Not run._\n";
  const head = "| Trace | Spans | Open (p50 / p95) | Sent to open | Full load (p50 / p95) | Full size | Browser first rows: explorer vs full | Browser heap: explorer vs full | Expand | Search | Agent steps | First open (index build) | Ingest | Checks |\n|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|---|\n";
  return head + rs.map((r) => {
    const b = r.browser;
    const ok = r.correct.every_span_once && r.correct.totals_match && r.correct.search_reveals;
    return `| ${r.shape} | ${r.spans.toLocaleString("en")} | ${ms(r.open_ms.p50)} / ${ms(r.open_ms.p95)} | ${mb(r.open_bytes)} | ${ms(r.full_ms.p50)} / ${ms(r.full_ms.p95)} | ${mb(r.full_bytes)} | ${b ? `${ms(b.windowed_first_rows_ms)} vs ${b.full_first_rows_ms === null ? b.full_failed : ms(b.full_first_rows_ms)}` : "not run"} | ${b ? `${b.windowed_heap_mb} vs ${b.full_heap_mb ?? "n/a"} MB` : ""} | ${ms(r.expand_ms.p50)} | ${ms(r.search_ms.p50)} | ${ms(r.graph_ms.p50)} | ${ms(r.cold_open_ms)} (${ms(r.index_build_ms)}) | ${r.ingest_spans_per_s.toLocaleString("en")}/s | ${ok ? "pass" : `**fail** ${JSON.stringify(r.correct)}`} |`;
  }).join("\n") + "\n";
};
const io = merged.filter((r) => r.full_io_ms);
const md = `# Benchmark report

Generated by \`npm run report\` on ${results.generated_at}, commit ${results.commit}. ${results.machine}; ClickHouse ${results.clickhouse}, local, one node; Next.js production build (\`next start\`).
Do not edit by hand.

**Open** is the explorer's first request for a trace: totals, the top level and the slowest path opened ${"six"} levels deep. **Full load** is the
same trace in one response, without inputs and outputs, which is what a trace view that builds the tree in the browser has to download.
Server times are wall-clock from the client, ${"p50 / p95"} over repeated requests. Browser times are from navigation start to the first tree rows on
screen in headless Chromium, median of three cold loads; heap is the JavaScript heap at that moment.

## Development traces

One shape (\`research-assistant\`), growing size. These are the traces the code was developed against.

${table("dev")}
## Held-out traces

Three shapes written before the run and never used while developing: wide fan-outs (\`batch-enricher\`), deep recursion (\`recursive-planner\`), and an
overnight run with hour-long idle gaps and lost parent spans (\`overnight-migration\`). The plan (shapes, size, seed, repeats) was pinned by hash
${results.pinned.heldout_sha256} at ${results.pinned.pinned_at || "n/a"} and run once.

${table("heldout")}
## Loading inputs and outputs too

The full load above leaves out inputs and outputs. With them:

${io.length ? "| Spans | Full load with I/O (p50) | Size |\n|--:|--:|--:|\n" + io.map((r) => `| ${r.spans.toLocaleString("en")} | ${ms(r.full_io_ms.p50)} | ${mb(r.full_io_bytes)} |`).join("\n") : "_Not run._"}

The explorer never sends inputs and outputs with the tree; the detail panel loads the first ${"16 KB"} of one span's input and output when it is selected.

## Checks

- **Every span once**: for traces up to 10,000 spans, the whole tree is walked through the paging API and every span must appear exactly once, under
  the parent the generator gave it. Above that, the stored index is checked instead: every span exactly once, inside its parent's range, one level
  deeper, with the generator's parent (or marked as missing its parent).
- **Totals match**: span count, failed spans and cost in the summary equal the generator and the raw observations.
- **Search reveals**: for every search hit, the branch the explorer opens equals the hit's chain of parents in the generator.
`;
writeFileSync("REPORT.md", md);

// The README's dashboard: a short table between markers, regenerated with the report so it never drifts.
if (existsSync("README.md")) {
  const pick = merged;
  const block = "<!-- results:start -->\n" +
    "| Trace | Set | Spans | Explorer: first rows | Full load: first rows | Heap, explorer vs full | Sent to open vs full | Expand a branch | Search | Checks |\n|---|---|--:|--:|--:|--:|--:|--:|--:|---|\n" +
    pick.map((r) => {
      const b = r.browser ?? {};
      const ok = r.correct.every_span_once && r.correct.totals_match && r.correct.search_reveals;
      return `| ${r.shape} | ${r.set === "dev" ? "development" : "held-out"} | ${r.spans.toLocaleString("en")} | ${ms(b.windowed_first_rows_ms)} | ${b.full_first_rows_ms === null ? b.full_failed : ms(b.full_first_rows_ms)} | ${b.windowed_heap_mb ?? "n/a"} vs ${b.full_heap_mb ?? "n/a"} MB | ${mb(r.open_bytes)} vs ${mb(r.full_bytes)} | ${ms(r.expand_ms.p50)} | ${ms(r.search_ms.p50)} | ${ok ? "pass" : "**fail**"} |`;
    }).join("\n") +
    `\n\n<sub>Generated by \`npm run report\` from reports/results.json (${results.generated_at}, ${results.machine}, ClickHouse ${results.clickhouse}). Browser: headless Chromium, navigation to first tree rows, median of three cold loads. Server times p50.</sub>\n<!-- results:end -->`;
  const readme = readFileSync("README.md", "utf8");
  writeFileSync("README.md", readme.replace(/<!-- results:start -->[\s\S]*<!-- results:end -->/, block));
}
console.log(`wrote reports/results.json, public/results.json, REPORT.md (${merged.length} rows)`);
process.exit(0);
